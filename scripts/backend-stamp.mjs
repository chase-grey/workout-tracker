/**
 * Keep the backend's version number honest.
 *
 *   npm run backend:stamp            # bump BACKEND_VERSION if SimpleBackend.gs changed
 *   npm run backend:stamp -- --check # say whether it needs bumping, exit 1 if so
 *
 * SimpleBackend.gs declares `BACKEND_VERSION`, which it answers at
 * ?route=version. The app ships the version it needs in
 * src/config/backendVersion.ts, next to a fingerprint of the backend file at that
 * version. When the two drift — the backend edited, the number not moved — the
 * test in scripts/backendVersion.test.mjs fails and says to run this. So a change
 * to the backend cannot ship without a bump, and the bump is what the app's
 * "backend is behind" banner and the deploy workflow's check compare against.
 *
 * The number is deliberately a counter, not the file hash: the app only needs to
 * ask "is the deployed one at least as new as me", and a hash can't answer that.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
export const BACKEND_FILE = path.join(root, 'SimpleBackend.gs')
export const CONFIG_FILE = path.join(root, 'src', 'config', 'backendVersion.ts')

const VERSION_LINE = /^const BACKEND_VERSION = (\d+)$/m

/** sha256 of the backend text with line endings normalised, so a CRLF checkout agrees with CI. */
export function fingerprintOf(text) {
  return createHash('sha256').update(text.replace(/\r\n/g, '\n')).digest('hex')
}

/** The BACKEND_VERSION the backend text declares. */
export function versionOf(text) {
  const m = text.match(VERSION_LINE)
  if (!m) throw new Error('SimpleBackend.gs has no `const BACKEND_VERSION = N` line')
  return Number(m[1])
}

/** The version and fingerprint the app currently ships, or zeros when the file is missing. */
export function readConfig(text) {
  const v = text.match(/REQUIRED_BACKEND_VERSION = (\d+)/)
  const f = text.match(/BACKEND_FINGERPRINT = '([0-9a-f]+)'/)
  return { version: v ? Number(v[1]) : 0, fingerprint: f ? f[1] : '' }
}

export function renderConfig(version, fingerprint) {
  return [
    '// Generated by `npm run backend:stamp`. Do not edit by hand.',
    '',
    '/**',
    ' * The SimpleBackend.gs version this build needs. The deployed backend answers',
    ' * its own at ?route=version; when that is lower, the app shows a banner and',
    ' * the deploy workflow fails (see BACKEND.md "Versioning").',
    ' */',
    `export const REQUIRED_BACKEND_VERSION = ${version}`,
    '',
    '/** sha256 of SimpleBackend.gs at that version, so a change without a bump fails the tests. */',
    `export const BACKEND_FINGERPRINT = '${fingerprint}'`,
    '',
  ].join('\n')
}

/**
 * Compare the backend file with what the app ships. `ok` when they agree;
 * otherwise `reason` says what moved.
 */
export function stampStatus(backendText, configText) {
  const version = versionOf(backendText)
  const fingerprint = fingerprintOf(backendText)
  const shipped = readConfig(configText)
  if (fingerprint === shipped.fingerprint && version === shipped.version) return { ok: true, version }
  const reason = version !== shipped.version
    ? `SimpleBackend.gs says BACKEND_VERSION = ${version} but the app ships ${shipped.version}`
    : `SimpleBackend.gs changed since version ${version} was stamped`
  return { ok: false, version, reason }
}

function readOr(file, fallback) {
  try {
    return readFileSync(file, 'utf8')
  } catch {
    return fallback
  }
}

export function stamp({ check = false } = {}) {
  const backend = readFileSync(BACKEND_FILE, 'utf8')
  const config = readOr(CONFIG_FILE, '')
  const status = stampStatus(backend, config)
  if (status.ok) {
    console.log(`Backend version ${status.version} is stamped and current.`)
    return 0
  }
  if (check) {
    console.error(`${status.reason}. Run: npm run backend:stamp`)
    return 1
  }
  // A hand-raised number is kept; an unchanged one moves up by one.
  const shipped = readConfig(config)
  const current = versionOf(backend)
  const next = current > shipped.version ? current : current + 1
  const bumped = backend.replace(VERSION_LINE, `const BACKEND_VERSION = ${next}`)
  writeFileSync(BACKEND_FILE, bumped)
  writeFileSync(CONFIG_FILE, renderConfig(next, fingerprintOf(bumped)))
  console.log(`Stamped backend version ${next}. Deploy it: npm run deploy:backend`)
  return 0
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(stamp({ check: process.argv.includes('--check') }))
}
